/**
 * Builds src/telegram/widget-html.ts from widget-src.ts: CSS and JS minified with esbuild (top-level functions keep
 * their names — onclick handlers call them), wrapped as the two widget documents Telegram takes. Run after editing
 * widget-src.ts: `npm run build:widgets`. The unit test rebuilds in memory and fails if the committed file is stale
 * or a widget is over 4096 bytes after zlib -9.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { transformSync } from 'esbuild';
import { CARD_JS, CSS, CSS_ITEMS, CSS_MENU, ITEMS_JS, MENU_JS } from '../src/telegram/widget-src.js';

export function buildWidgets() {
  const css = (extra = '') => transformSync(CSS + extra, { loader: 'css', minify: true, charset: 'utf8' }).code.trim();
  const js = (src: string) => transformSync(src, { loader: 'js', minify: true, target: 'es2015', charset: 'utf8' }).code.trim();
  const doc = (code: string, extra?: string) => `<style>${css(extra)}</style><body><div id="a"></div><script>${code}</script>`;
  // .pr (a big price) is in the shared CSS: the items and the card both show one.
  return { menu: doc(js(MENU_JS), CSS_MENU), items: doc(js(ITEMS_JS), CSS_ITEMS), card: doc(js(CARD_JS)) };
}

export function widgetHtmlModule() {
  const { menu, items, card } = buildWidgets();
  return [
    '// Generated by scripts/build-widgets.ts from widget-src.ts — do not edit; run `npm run build:widgets`.',
    `export const MENU_HTML = ${JSON.stringify(menu)};`,
    `export const ITEMS_HTML = ${JSON.stringify(items)};`,
    '/** The shop menu as /menu sends it (home). */',
    'export const WIDGET_HTML = MENU_HTML;',
    `export const CARD_HTML = ${JSON.stringify(card)};`,
    '/** Deal cards are cards with «Принять / Отклонить» (state.a). */',
    'export const NOTICE_HTML = CARD_HTML;',
    '',
  ].join('\n');
}

if (process.argv[1]?.endsWith('build-widgets.ts')) {
  writeFileSync(join(import.meta.dirname, '..', 'src', 'telegram', 'widget-html.ts'), widgetHtmlModule());
  console.log('src/telegram/widget-html.ts written');
}
